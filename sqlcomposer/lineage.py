NodeId = str
"""A Lineage node id. Either `db.table.column` for a Source column - identical to
`ColumnRef.qualified` - or `<case name>:<output column>` for a Case's output. The two forms
cannot collide because a Case name may not contain a colon and a qualified column always
contains exactly two dots."""

ROLE_METRIC = "metric"
ROLE_DIMENSION = "dimension"
ROLE_FILTER = "filter"
ROLE_JOIN_KEY = "join_key"
"""Edge `role` values. Every edge carries exactly one, so a reader can ask "which columns
does this number actually come from" and exclude the ones that only joined or narrowed
it."""

_KIND_COLUMN = "column"
_KIND_OUTPUT = "output"
"""Node `kind` values. Private because the contract is the two strings, not these names."""

_ROLE_RANK = {
    ROLE_METRIC: 3,
    ROLE_DIMENSION: 3,
    ROLE_FILTER: 2,
    ROLE_JOIN_KEY: 1,
}
"""A DiGraph holds one edge per ordered pair, so a column that both IS a number and also
narrows it or carries a join has to collapse to a single role. The stronger claim wins: "this
column is the number" outranks "this column only narrowed it", which outranks "this column
only carried a join". Collapsing the other way would let a `dt` that is both the Grain and the
Partition filter print as a filter and read as if the breakdown came from nowhere."""

_MANIFEST_VERSION = 1


@dataclass(frozen=True)
class Lineage:
    """Which Source columns feed each output column of a Case, and the Join path taken.

    `graph` is a `networkx.DiGraph` whose edges point DOWNSTREAM - from a Source column to
    the output that consumes it - so `networkx.ancestors(graph, output)` is the answer to
    "where did this number come from" and the graph reads the same direction as the data.

    Node attributes: every node carries `kind` ("column" or "output"); a column node carries
    `type` (the declared Hive type) and `partition`; an output node carries `role`
    ("dimension" or "metric") and, for a metric, `rule` (its `ReAggregation` value) and
    `native` (the Grain it was rolled up from, or None).

    `rule` and `native` are the live objects - a `ReAggregation` member and a `Grain`, not
    their string forms. The graph is an in-memory structure, and a reader asking whether a
    number rolled up by SUM should be able to compare against `ReAggregation.SUM` rather than
    re-parse a string; the string forms exist only in `to_json`, `to_text` and `to_dot`.

    Edge attributes: `role`, one of the ROLE_ constants; and for a filter edge, `filter`
    (the Filter's name); for a metric edge, `metric` (the Metric's name).

    `path` is the Join path as edge names, recorded because decision 4 requires the chosen
    path to be part of the Lineage - two Join paths between the same Sources give the same
    column-level graph and different numbers.

    Output order is the graph's node insertion order, which `build`, `trace_through` and
    `Manifest.from_json` all preserve. It is `Case.output_names`: Dimensions in Grain order,
    then Metrics sorted by name.
    """

    graph: networkx.DiGraph
    case: str
    path: tuple[str, ...]

    def outputs(self) -> tuple[str, ...]:
        """Every output column name, in the Case's output order."""
        prefix = f"{self.case}:"
        return tuple(
            node[len(prefix) :]
            for node, data in self.graph.nodes(data=True)
            if data.get("kind") == _KIND_OUTPUT and node.startswith(prefix)
        )

    def upstream(self, output_column: str) -> frozenset[NodeId]:
        """Every Source column feeding one output column, transitively.

        Takes the bare output name (`failure_rate`), not the prefixed node id. Includes
        columns reached through Filters and join keys; walk `graph.in_edges(..., data=True)`
        and read each edge's `role` if you want only the measured ones.

        Refuses an output this Case does not publish rather than returning an empty set: an
        empty answer to "where did this number come from" is indistinguishable from a
        misspelled output name, and one of those is a wrong review.
        """
        node = output_id(self.case, output_column)
        if node not in self.graph:
            raise InvalidDeclaration(
                subject=f"{self.case}:{output_column}",
                problem=f"Case {self.case!r} publishes no output column "
                f"{output_column!r}",
                remedy="use one of the names Lineage.outputs() reports",
                outputs=", ".join(self.outputs()) or "(none)",
            )
        return frozenset(
            found
            for found in networkx.ancestors(self.graph, node)
            if self.graph.nodes[found].get("kind") == _KIND_COLUMN
        )

    def downstream(self, column: NodeId) -> frozenset[str]:
        """Every output column of this Case that a given Source column feeds.

        The impact question: "if this warehouse column changes, which numbers move".

        Deliberately asymmetric with `upstream`: a column this Case never reads answers with
        the empty set rather than refusing, because "none of them" is the true answer to the
        impact question and a caller sweeping every column of a changed table would
        otherwise have to guard every call.
        """
        if column not in self.graph:
            return frozenset()
        prefix = f"{self.case}:"
        return frozenset(
            found[len(prefix) :]
            for found in networkx.descendants(self.graph, column)
            if self.graph.nodes[found].get("kind") == _KIND_OUTPUT and found.startswith(prefix)
        )

    def columns(self) -> frozenset[NodeId]:
        """Every Source column node in the graph."""
        return frozenset(
            node
            for node, data in self.graph.nodes(data=True)
            if data.get("kind") == _KIND_COLUMN
        )


def node_id(ref: ColumnRef) -> NodeId:
    """`db.table.column`. Identical to `ColumnRef.qualified`, and exists only so callers
    reading the graph do not have to know that."""
    return ref.qualified


def output_id(case: str, output_column: str) -> NodeId:
    """`<case>:<output column>` - the node id of one of a Case's output columns.

    Refuses a Case name containing a colon. Nothing else in the library enforces that, and
    the whole no-collision argument for this node id scheme rests on it: with two colons in
    play, splitting a node id back into (case, output) stops being unambiguous and a graph
    read from a Manifest starts pointing at the wrong thing.
    """
    if ":" in case:
        raise InvalidDeclaration(
            subject=f"case:{case}",
            problem=f"Case name {case!r} contains a colon, which separates a Case from its "
            "output column in every Lineage node id",
            remedy="rename the Case; a colon makes its node ids ambiguous",
        )
    return f"{case}:{output_column}"


