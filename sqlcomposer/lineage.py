def manifests_for_reads(registry: Registry, case: Case) -> tuple[Manifest, ...]:
    """A Manifest for every written Source this Case reads, transitively, sorted by Source.

    The hop that makes decision 7's two halves one thing. A Manifest needs a plan and a
    plan needs no `run_date`, so the Manifests a static artifact traces through are
    derivable from the Declarations alone - exactly like the artifact itself. Nothing here
    runs anything or reads a file.

    Transitive because a written Source can be read by the Case that writes another one:
    `Registry.writing_case` answers who wrote each Source, and following that answer from
    the producer's own Sources reaches the atomic tables at the end of the chain. A cycle -
    which `write.plan` refuses as a statement order - terminates here on the visited set
    rather than spinning.

    Raises whatever planning a producing Case raises. That is wanted: an artifact that
    traced through a Case which no longer compiles would describe numbers nobody can produce.
    """
    from sqlcomposer import compile as compile_module  # local: see static_lineage

    found: dict[str, Manifest] = {}
    pending = [case]
    seen_cases = {case.name}
    while pending:
        reading = pending.pop()
        for source in sorted(reading.sources(registry), key=lambda item: item.qualified):
            producer = registry.writing_case(source)
            if producer is None or source.qualified in found:
                continue
            producer_plan = compile_module.plan(registry, producer)
            found[source.qualified] = manifest_for(registry, producer_plan, source)
            if producer.name not in seen_cases:
                seen_cases.add(producer.name)
                pending.append(producer)
    return tuple(found[key] for key in sorted(found))


def static_lineage(registry: Registry, case: Case) -> str:
    """The git-tracked text artifact for one Case.

    Derivable from the Case definition with nothing running: the resolved Metric family, the
    Grain, the Filters, the chosen Join path and the column-level tree. Regenerating this
    and diffing it is what makes `Case.variant()` and late Tag binding reviewable - both of
    them change a Case's SQL from a file that does not mention it.

    Goes through `compile.plan`, which means it also runs every refusal - an ambiguous Join
    path or an unprovable re-grain raises here rather than producing an artifact. That is
    wanted: an artifact regenerated in CI is then also a check that every declared Case still
    compiles.

    A Case that reads a written Source gets TWO trees. The first is what the statement
    literally reads, stopping at the written table's own columns; the second traces through
    that table's Manifest to the Sources the numbers actually came from. Both are here on
    purpose: the first is the SQL under review, and the second is the answer to "where did
    this number come from", which is the question decision 7 exists for. Without it the
    committed record for a Case reading a written table stops at a table rather than at
    Sources - and editing the producing Case's Filters, which is exactly the action at a
    distance this artifact defends against, would leave the file byte-identical.

    No `run_date` is bound anywhere, including in the Manifests. Planning resolves Tags, the
    Join path and the re-grain proofs, none of which look at a deferred value, so a Case
    whose Filters hold a `RunDate` has a static Lineage just like any other - only rendering
    it to SQL would refuse.
    """
    # Local import: compile imports this module at module scope, so the dependency has to
    # run in this direction only when someone actually asks for an artifact.
    from sqlcomposer import compile as compile_module

    plan = compile_module.plan(registry, case)
    lineage = build(registry, plan)
    manifests = manifests_for_reads(registry, case)

    lines = [
        f"case: {case.name}",
        f"grain: {case.grain}",
        f"spine: {plan.spine.qualified}",
        f"sources: {', '.join(source.qualified for source in plan.sources)}",
        f"join path: {_path_text(lineage.path)}",
        f"metrics: "
        f"{', '.join(item.metric.name for item in plan.metrics) or '(none)'}",
        f"filters: {', '.join(item.name for item in plan.filters) or '(none)'}",
    ]
    if case.writes_to is not None:
        lines.append(f"writes: {case.writes_to.qualified}")
    if manifests:
        lines.append(
            "traces through: "
            + ", ".join(
                f"{manifest.source} (written by {manifest.written_by})"
                for manifest in manifests
            )
        )
    if case.note:
        lines.append(f"note: {case.note}")
    lines.append("")
    lines.append("as read:")
    lines.append(to_text(lineage))
    if manifests:
        lines.append("")
        lines.append("traced to source:")
        lines.append(to_text(trace_through(lineage, manifests)))
    return "\n".join(lines) + "\n"


def write_static_lineage(registry: Registry, directory: str | Path) -> tuple[Path, ...]:
    """Write one static Lineage file per declared Case into `directory`.

    One file per Case, named `<case name>.txt`, so a diff points at the Case that moved.
    Returns the paths written, sorted. Overwrites; it is regenerated output, and a CI job
    that regenerates and diffs is the intended use.

    Written UTF-8 with explicit `\\n` line endings: the artifact is committed, and a
    regeneration on Windows that only changed the line endings would show every line of
    every file as modified.
    """
    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for case in registry.cases():
        path = target / f"{case.name}.txt"
        path.write_text(static_lineage(registry, case), encoding="utf-8", newline="\n")
        written.append(path)
    return tuple(sorted(written))


def write_manifests(registry: Registry, directory: str | Path) -> tuple[Path, ...]:
    """Write one Manifest per written Source into `directory`, as `<db>.<table>.json`.

    The writer `Manifest.from_json` was missing. A Manifest round-trips through JSON
    precisely so a reader in another process can trace through a written table without
    re-deriving it, and until something wrote one, that reader had no file to open and
    `Registry.resolve_column`'s reason for existing ("when a Manifest or a static Lineage
    artifact is read back from disk") described a workflow nothing provided.

    Derived from the Declarations with nothing running and no `run_date`, exactly like the
    static Lineage artifact beside it, so both are regenerated by the same command and
    diffed in the same review. Overwrites; regenerated output.

    Named by the written Source rather than by the producing Case, because that is the key a
    reader has: they hold a table name and want the Manifest for it.
    """
    from sqlcomposer import compile as compile_module  # local: see static_lineage

    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for case in registry.cases():
        if case.writes_to is None:
            continue
        source = registry.source(case.writes_to.qualified)
        manifest = manifest_for(registry, compile_module.plan(registry, case), source)
        path = target / f"{source.qualified}.json"
        path.write_text(manifest.to_json() + "\n", encoding="utf-8", newline="\n")
        written.append(path)
    return tuple(sorted(written))
