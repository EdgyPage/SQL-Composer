def _add_column(graph: networkx.DiGraph, ref: ColumnRef) -> NodeId:
    """Add (or find) the node for a Source column, carrying its declared facts."""
    node = node_id(ref)
    if node not in graph:
        graph.add_node(node, kind=_KIND_COLUMN, type=ref.type, partition=ref.partition)
    return node


def _add_edge(
    graph: networkx.DiGraph,
    frm: NodeId,
    to: NodeId,
    *,
    role: str,
    **attrs: Any,
) -> None:
    """Add a downstream edge, keeping the strongest role when one already exists.

    Replaces rather than updates the attribute dict, so a `filter` name cannot survive on an
    edge that has been promoted to a metric edge.
    """
    existing = graph.get_edge_data(frm, to)
    if existing is not None:
        if _ROLE_RANK[existing["role"]] >= _ROLE_RANK[role]:
            return
        graph.remove_edge(frm, to)
    graph.add_edge(frm, to, role=role, **attrs)


def _measured_columns(metric: Metric) -> tuple[ColumnRef, ...]:
    """The columns a Metric actually aggregates, components included.

    Not `Metric.columns`, which also carries the scoped `when`'s columns: those narrow the
    number rather than being it, and the two want different edge roles. A `COUNT(*)` Metric
    returns nothing here - it measures rows, not a column - so its output node carries no
    metric edge at all. That is honest rather than a gap: the Source it counts is named by
    the plan's spine and path, which is what the static artifact's header prints.
    """
    refs: list[ColumnRef] = []
    if metric.column is not None:
        refs.append(metric.column)
    for part in metric.components:
        refs.extend(_measured_columns(part))
    return tuple(refs)


def _scoped_filters(metric: Metric) -> tuple[Filter, ...]:
    """Every `when` Filter scoped to this Metric, components included, first mention first."""
    found: list[Filter] = []
    seen: set[str] = set()
    if metric.when is not None:
        found.append(metric.when)
        seen.add(metric.when.name)
    for part in metric.components:
        for scoped in _scoped_filters(part):
            if scoped.name not in seen:
                found.append(scoped)
                seen.add(scoped.name)
    return tuple(found)


def _sorted_refs(refs: Iterable[ColumnRef]) -> tuple[ColumnRef, ...]:
    """Column refs in qualified-name order, so edge insertion is stable between runs."""
    return tuple(sorted(refs, key=lambda ref: ref.qualified))


def build(registry: Registry, plan: CasePlan) -> Lineage:
    """Derive the Lineage of a planned Case from the plan itself.

    Adds one node per output column and one per Source column the plan reaches, then edges:
    each Metric's measured columns to its output (role `metric`), each Dimension's column to
    its output (role `dimension`), each Case-level Filter's columns to EVERY output (role
    `filter`, because a WHERE clause narrows every number in the Case), each Metric-scoped
    Filter's columns to that Metric's output only (also role `filter`, because it narrows
    rather than measures), and each join key on both sides to every output (role
    `join_key`).

    Reads `plan.dimensions`, `plan.metrics`, `plan.filters` and `plan.path` - never
    `plan.case` - for everything except the Case's name. The plan is what `compile.build`
    renders, so a plan whose Filters differ from its Case's produces a Lineage of the
    statement that will run rather than of the Case that was declared.

    `registry` is taken first by the library-wide convention and is not consulted: every
    fact this graph records is already on the plan, and re-deriving any of it from the
    Registry would let the artifact disagree with the SQL. It stays in the signature because
    resolving a written Source's Manifest belongs here if this ever stops being true.

    Authoritative. Never cross-checked against `sqlglot.lineage` at runtime.
    """
    case_name = plan.case.name
    graph = networkx.DiGraph()

    # Output nodes first and in output order: node insertion order IS `outputs()`.
    for dimension in plan.dimensions:
        _add_output(graph, case_name, dimension.name, role=ROLE_DIMENSION)
    for metric_plan in plan.metrics:
        _add_output(
            graph,
            case_name,
            metric_plan.metric.name,
            role=ROLE_METRIC,
            rule=metric_plan.rule,
            native=metric_plan.native,
        )
    every_output = tuple(
        node
        for node, data in graph.nodes(data=True)
        if data.get("kind") == _KIND_OUTPUT
    )

    for dimension in plan.dimensions:
        target = output_id(case_name, dimension.name)
        for ref in _sorted_refs(dimension.columns):
            _add_edge(graph, _add_column(graph, ref), target, role=ROLE_DIMENSION)

    for metric_plan in plan.metrics:
        metric = metric_plan.metric
        target = output_id(case_name, metric.name)
        for ref in _sorted_refs(_measured_columns(metric)):
            _add_edge(
                graph,
                _add_column(graph, ref),
                target,
                role=ROLE_METRIC,
                metric=metric.name,
            )
        for scoped in _scoped_filters(metric):
            for ref in _sorted_refs(scoped.columns):
                _add_edge(
                    graph,
                    _add_column(graph, ref),
                    target,
                    role=ROLE_FILTER,
                    filter=scoped.name,
                )

    for case_filter in plan.filters:
        for ref in _sorted_refs(case_filter.columns):
            node = _add_column(graph, ref)
            for target in every_output:
                _add_edge(graph, node, target, role=ROLE_FILTER, filter=case_filter.name)

    for step in plan.path:
        for left, right in step.keys:
            for ref in (left, right):
                node = _add_column(graph, ref)
                for target in every_output:
                    _add_edge(graph, node, target, role=ROLE_JOIN_KEY)

    return Lineage(graph=graph, case=case_name, path=plan.join_names)


def _add_output(
    graph: networkx.DiGraph,
    case: str,
    name: str,
    *,
    role: str,
    **attrs: Any,
) -> NodeId:
    """Add one output node, refusing a duplicate output name.

    Two outputs publishing the same name would collapse to one node here and to one INSERT
    column downstream - the Grain already refuses it between Dimensions, but a Metric named
    after a Dimension is only caught here.
    """
    node = output_id(case, name)
    if node in graph:
        raise InvalidDeclaration(
            subject=f"case:{case}",
            problem=f"two output columns of {case!r} are both named {name!r}",
            remedy="rename the Metric, or give the Dimension an explicit `alias=`; output "
            "names are Lineage node ids and INSERT columns",
        )
    graph.add_node(node, kind=_KIND_OUTPUT, role=role, **attrs)
    return node


