def _rule_text(rule: Any) -> str:
    return rule.value if isinstance(rule, ReAggregation) else str(rule)


def _edge_text(data: dict[str, Any]) -> str:
    """How one edge prints: its role, plus the name that explains it."""
    role = data.get("role", "")
    if role == ROLE_FILTER and data.get("filter"):
        return f"{role} {data['filter']}"
    if role == ROLE_METRIC and data.get("metric"):
        return f"{role} {data['metric']}"
    return role


def _output_text(data: dict[str, Any]) -> str:
    """How one output node prints: its role and, for a Metric, how it was re-aggregated."""
    role = data.get("role", "")
    if role != ROLE_METRIC:
        return role
    native: Grain | None = data.get("native")
    where = str(native) if native is not None else "atomic rows"
    return f"{role} rule={_rule_text(data.get('rule'))} from={where}"


def _path_text(path: Sequence[str]) -> str:
    return " -> ".join(path) or "(direct)"


def _tree_lines(
    graph: networkx.DiGraph,
    node: NodeId,
    depth: int,
    stack: tuple[NodeId, ...],
) -> list[str]:
    """One indented line per contributing column, deepest-last, sorted by node id.

    Recursive because `trace_through` makes the graph deeper than two levels: a column on a
    written Source has the Manifest's own upstream columns hanging off it.
    """
    lines: list[str] = []
    for parent in sorted(graph.predecessors(node)):
        data = graph.edges[parent, node]
        marker = "  (cycle)" if parent in stack else ""
        lines.append(f"{'  ' * depth}{parent}  [{_edge_text(data)}]{marker}")
        if not marker:
            lines.extend(_tree_lines(graph, parent, depth + 1, stack + (parent,)))
    return lines


def to_text(lineage: Lineage, output_column: str | None = None) -> str:
    """A text tree of where each output column comes from.

    One block per output column, or just the named one. Children are sorted by node id so
    the output is stable enough to paste into a review comment, and each edge prints its
    role, so a column that only narrows a number is visibly different from one that is the
    number. Ends with the Join path.

    ASCII only, and indentation rather than box-drawing characters: this is printed to a
    Windows terminal as often as to a Unix one, and a `UnicodeEncodeError` in the middle of
    a refusal is a worse outcome than a plainer tree.
    """
    outputs = lineage.outputs()
    if output_column is not None:
        if output_column not in outputs:
            raise InvalidDeclaration(
                subject=f"{lineage.case}:{output_column}",
                problem=f"Case {lineage.case!r} publishes no output column "
                f"{output_column!r}",
                remedy="use one of the names Lineage.outputs() reports",
                outputs=", ".join(outputs) or "(none)",
            )
        outputs = (output_column,)

    lines = [lineage.case]
    for name in outputs:
        node = output_id(lineage.case, name)
        lines.append(f"  {name}  [{_output_text(lineage.graph.nodes[node])}]")
        contributors = _tree_lines(lineage.graph, node, 2, (node,))
        lines.extend(contributors or ["    (no declared column feeds this output)"])
    lines.append(f"  join path: {_path_text(lineage.path)}")
    return "\n".join(lines)


def _dot_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def _dot_label(*parts: str) -> str:
    """A DOT label: each part escaped, then joined by a literal backslash-n."""
    return "\\n".join(_dot_escape(part) for part in parts if part)


_DOT_EDGE_STYLE = {
    ROLE_METRIC: 'style="solid"',
    ROLE_DIMENSION: 'style="solid", color="gray40"',
    ROLE_FILTER: 'style="dashed"',
    ROLE_JOIN_KEY: 'style="dotted", color="gray60"',
}


def to_dot(lineage: Lineage, name: str = "lineage") -> str:
    """The graph as a DOT string.

    A string, not a file and not a rendered image: DOT is a text format, so there is no
    graphviz dependency to install and the output diffs. Source columns and outputs are
    given different shapes, and edge roles become edge styles.

    Column nodes come out sorted and outputs in output order, and the edge list is sorted,
    so re-exporting an unchanged Lineage is a byte-identical file.
    """
    graph = lineage.graph
    lines = [f'digraph "{_dot_escape(name)}" {{']
    lines.append("  rankdir=LR;")
    lines.append(
        f'  graph [label="{_dot_label(lineage.case, "join path: " + _path_text(lineage.path))}",'
        ' labelloc="t"];'
    )
    lines.append('  node [fontname="Helvetica", fontsize=10];')

    for node in sorted(lineage.columns()):
        data = graph.nodes[node]
        shape = "box3d" if data.get("partition") else "box"
        label = _dot_label(node, str(data.get("type", "")))
        lines.append(f'  "{_dot_escape(node)}" [shape="{shape}", label="{label}"];')

    for output in lineage.outputs():
        node = output_id(lineage.case, output)
        data = graph.nodes[node]
        label = _dot_label(output, _output_text(data))
        lines.append(f'  "{_dot_escape(node)}" [shape="ellipse", label="{label}"];')

    for frm, to in sorted(graph.edges()):
        data = graph.edges[frm, to]
        style = _DOT_EDGE_STYLE.get(data.get("role", ""), 'style="solid"')
        lines.append(
            f'  "{_dot_escape(frm)}" -> "{_dot_escape(to)}" '
            f'[{style}, label="{_dot_label(_edge_text(data))}"];'
        )

    lines.append("}")
    return "\n".join(lines)


