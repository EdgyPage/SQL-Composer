def _grain_to_json(grain: Grain | None) -> list[dict[str, Any]] | None:
    """A Grain as its Dimensions' qualified columns, buckets and aliases.

    Not just the output names: a Dimension's identity is the column it reads, and a Grain
    read back from output names alone could not be compared against another Grain by column,
    which is exactly what the re-grain check does.
    """
    if grain is None:
        return None
    return [
        {
            "column": dimension.column.qualified,
            "bucket": dimension.bucket.value if dimension.bucket is not None else None,
            "alias": dimension.alias,
            "note": dimension.note,
        }
        for dimension in grain.dimensions
    ]


def _grain_from_json(data: Any, registry: Registry) -> Grain | None:
    if data is None:
        return None
    return Grain(
        dimensions=tuple(
            Dimension(
                column=registry.resolve_column(item["column"]),
                bucket=TimeBucket(item["bucket"]) if item.get("bucket") else None,
                alias=item.get("alias"),
                note=item.get("note", ""),
            )
            for item in data
        )
    )


def _lineage_to_json(lineage: Lineage) -> dict[str, Any]:
    nodes: list[dict[str, Any]] = []
    for node, data in lineage.graph.nodes(data=True):
        if data.get("kind") == _KIND_COLUMN:
            nodes.append(
                {
                    "id": node,
                    "kind": _KIND_COLUMN,
                    "type": data.get("type"),
                    "partition": bool(data.get("partition")),
                }
            )
        else:
            entry: dict[str, Any] = {"id": node, "kind": _KIND_OUTPUT, "role": data.get("role")}
            if "rule" in data:
                entry["rule"] = _rule_text(data["rule"])
            if "native" in data:
                entry["native"] = _grain_to_json(data["native"])
            nodes.append(entry)
    edges: list[dict[str, Any]] = []
    for frm, to, data in lineage.graph.edges(data=True):
        edge: dict[str, Any] = {"from": frm, "to": to, "role": data.get("role")}
        for key in ("filter", "metric"):
            if key in data:
                edge[key] = data[key]
        edges.append(edge)
    return {
        "case": lineage.case,
        "path": list(lineage.path),
        "nodes": nodes,
        "edges": edges,
    }


def _lineage_from_json(data: dict[str, Any], registry: Registry) -> Lineage:
    graph = networkx.DiGraph()
    for entry in data["nodes"]:
        node = entry["id"]
        if entry.get("kind") == _KIND_COLUMN:
            # Re-resolving is the point of taking a Registry: a column that has left the
            # Declarations refuses here rather than tracing to something that is gone. The
            # declared type and partitioning are then taken from TODAY's Declaration - a
            # retyped column is Drift, and verify.py owns that report.
            ref = registry.resolve_column(node)
            graph.add_node(node, kind=_KIND_COLUMN, type=ref.type, partition=ref.partition)
        else:
            attrs: dict[str, Any] = {"kind": _KIND_OUTPUT, "role": entry.get("role")}
            if "rule" in entry:
                attrs["rule"] = ReAggregation(entry["rule"])
            if "native" in entry:
                attrs["native"] = _grain_from_json(entry["native"], registry)
            graph.add_node(node, **attrs)
    for entry in data["edges"]:
        attrs = {"role": entry["role"]}
        for key in ("filter", "metric"):
            if key in entry:
                attrs[key] = entry[key]
        graph.add_edge(entry["from"], entry["to"], **attrs)
    return Lineage(graph=graph, case=data["case"], path=tuple(data["path"]))


@dataclass(frozen=True)
class Manifest:
    """The Lineage a written Source carries.

    This is what lets a later Case reading a written table trace through it to the true
    upstream Sources instead of stopping at the written table - and what lets a re-grain
    check know the Grain the stored numbers were written at.

    `source` is the written Source's qualified name, as a string rather than a Source object
    so a Manifest round-trips through JSON without the Registry.

    `lineage.case` is the producing Case, so the Manifest's own output nodes are
    `<producing case>:<column>` while the table's columns are `<source>.<column>`. Those are
    the two ends `trace_through` splices together, matched by output name - which is the
    same match `Registry.metric_behind` makes, and the reason `Case.output_names` has to
    stay stable.
    """

    source: str
    written_by: str
    written_at: Grain
    lineage: Lineage

    def to_json(self) -> str:
        """Serialise. The written Grain is recorded as its Dimensions' qualified columns,
        buckets and aliases, and the graph as a node/edge list with every attribute - a
        Manifest read back must answer the same questions as the one that was written.

        Indented and in graph order rather than sorted: a Manifest is a checked-in artifact,
        and stable ordering plus one key per line is what makes its diff readable."""
        return json.dumps(
            {
                "version": _MANIFEST_VERSION,
                "source": self.source,
                "written_by": self.written_by,
                "written_at": _grain_to_json(self.written_at),
                "lineage": _lineage_to_json(self.lineage),
            },
            indent=2,
        )

    @classmethod
    def from_json(cls, text: str, registry: Registry) -> Manifest:
        """Read a Manifest back, re-resolving every column node through the Registry.

        Raises `UndeclaredColumn` or `UndeclaredSource` if the Declarations have moved since
        the Manifest was written - a Manifest that no longer type-checks against the
        Declarations is worse than no Manifest, because it would trace to columns that are
        gone.
        """
        data = json.loads(text)
        version = data.get("version")
        if version != _MANIFEST_VERSION:
            raise InvalidDeclaration(
                subject=f"manifest:{data.get('source', '(unknown)')}",
                problem=f"Manifest format version {version!r} is not readable by this "
                f"library, which writes version {_MANIFEST_VERSION}",
                remedy="regenerate the Manifest with the current version of the composer",
            )
        registry.source(data["source"])  # refuses a Manifest for a table nobody declares
        return cls(
            source=data["source"],
            written_by=data["written_by"],
            written_at=_grain_from_json(data["written_at"], registry) or Grain(),
            lineage=_lineage_from_json(data["lineage"], registry),
        )


def manifest_for(registry: Registry, plan: CasePlan, target: Source) -> Manifest:
    """The Manifest a write of this plan into `target` should carry.

    `written_at` is the plan's Case's Grain. Raises `InvalidDeclaration` when `target` does
    not declare a column for every output name, because a Manifest that describes columns
    the table does not have will mis-trace the first Case that reads it.

    Note which Grain that is: the PRODUCING Case's Grain, whose Dimensions point at the
    upstream Sources' columns, not at `target`'s own. `Registry.native_grain` is the one that
    re-points a written Source's Grain at its own columns, and a re-grain check wants that
    one. This records where the numbers came from; that one records what they are now keyed
    by.
    """
    missing = tuple(name for name in plan.output_names if not target.has(name))
    if missing:
        raise InvalidDeclaration(
            subject=f"source:{target.qualified}",
            problem=f"Case {plan.case.name!r} publishes {', '.join(missing)}, which "
            f"{target.qualified} does not declare",
            remedy="regenerate the Declaration for the written table, or correct the "
            "Case's Metric names and Grain so they match its columns",
            declared=", ".join(column.name for column in target.columns) or "(none)",
        )
    return Manifest(
        source=target.qualified,
        written_by=plan.case.name,
        written_at=plan.case.grain,
        lineage=build(registry, plan),
    )


def _graft(
    graph: networkx.DiGraph,
    upstream: networkx.DiGraph,
    output_node: NodeId,
    onto: NodeId,
) -> None:
    """Copy everything feeding `output_node` in `upstream` into `graph`, landing on `onto`.

    The Manifest's output node is not copied: it IS the written table's column, and keeping
    both would put two nodes in the graph for one number.
    """
    feeding = networkx.ancestors(upstream, output_node)
    inside = feeding | {output_node}
    for node in feeding:
        if node not in graph:
            graph.add_node(node, **dict(upstream.nodes[node]))
    for frm, to, data in upstream.edges(data=True):
        if frm not in inside or to not in inside:
            continue
        attrs = dict(data)
        role = attrs.pop("role")
        _add_edge(
            graph,
            onto if frm == output_node else frm,
            onto if to == output_node else to,
            role=role,
            **attrs,
        )


def trace_through(lineage: Lineage, manifests: Sequence[Manifest]) -> Lineage:
    """Splice each written Source's Manifest into a Lineage that reads it.

    Where `lineage` has a column node on a written Source, the matching Manifest's graph is
    grafted in so that the leaves become the true upstream Sources. Manifests that match no
    node in `lineage` are ignored; a written Source with no Manifest is left as a leaf, which
    is honest - the trace genuinely stops there. So is a column of a written Source that its
    producing Case does not publish (a Partition column the write adds, say): no Manifest
    output matches it, and it stays a leaf.

    Runs to a fixed point, so a chain of written Sources - A feeds B feeds the Case - traces
    all the way back in one call, and each (Manifest, column) pair is grafted at most once so
    a cyclic set of Manifests terminates instead of spinning.

    Returns a new Lineage; does not mutate the one passed in.
    """
    graph = lineage.graph.copy()
    by_source: dict[str, Manifest] = {}
    for manifest in manifests:
        by_source.setdefault(manifest.source, manifest)

    grafted: set[tuple[str, NodeId]] = set()
    changed = True
    while changed:
        changed = False
        for node in [
            found
            for found, data in list(graph.nodes(data=True))
            if data.get("kind") == _KIND_COLUMN
        ]:
            source_name, _, column_name = node.rpartition(".")
            manifest = by_source.get(source_name)
            if manifest is None or (source_name, node) in grafted:
                continue
            produced = output_id(manifest.lineage.case, column_name)
            if produced not in manifest.lineage.graph:
                continue
            grafted.add((source_name, node))
            _graft(graph, manifest.lineage.graph, produced, node)
            changed = True

    return Lineage(graph=graph, case=lineage.case, path=lineage.path)


