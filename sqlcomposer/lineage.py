"""Builder-derived, column-level Lineage: the graph, its exports, and the Manifest.

The Lineage this library emits is derived from the CasePlan, not from the SQL. That is a
deliberate inversion of the obvious design, and the reason is that sqlglot's own
`lineage()` disables qualify's validation internally and degrades silently: an unresolvable
source becomes a placeholder leaf, a star without a schema becomes a leaf named `"*"`, an
unknown subquery scope only logs a warning. Anything built on it would report a
confident-looking graph with holes in it. So builder-derived lineage is AUTHORITATIVE at
runtime, and `sqlglot.lineage` appears only in the test suite as a cross-check - never as
validation.

Node identity is the fully-qualified `db.table.column` a contributor typed in a Declaration.
Nothing re-derives it: `ColumnRef.qualified` is the string, everywhere.

The static Lineage artifact is the git-tracked output of this module. It is derivable from a
Case definition without running anything, regenerated by a command, and diffable in review -
which is the only defence against `Case.variant()`'s action at a distance and against late
Tag-family binding changing a Case nobody edited. Nothing written here carries a timestamp
or a host name for exactly that reason: an artifact that changes when nothing changed is an
artifact reviewers learn to skip.

Everything in this module reads the plan, never the AST and never the SQL text. The plan is
what `compile.build` renders, so the graph describes the statement that will actually run -
including its Filters and its Join path, both of which move numbers without appearing in any
column-to-column mapping a parser could recover.
"""
